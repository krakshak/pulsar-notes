"""Pydantic schemas for Ollama structured output, SQLite data models, and REST API.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


# ==============================================================================
# Ollama Structured Output Schemas (LLM Extraction Contract)
# ==============================================================================

class ExtractedActionItem(BaseModel):
    """Action item extracted from spoken meeting transcript."""
    owner: str = Field(
        ...,
        description="'Me' if spoken/committed by [Me], otherwise the person's name",
    )
    task: str = Field(
        ...,
        description="Concrete, actionable task description",
    )
    due_date: Optional[str] = Field(
        default=None,
        description="Deadline or timeframe if mentioned (e.g., 'Friday', 'next Tuesday', '2026-11-15')",
    )


class TopicTakeaway(BaseModel):
    """Slack AI-style grouped topic section with bulleted key takeaways."""
    topic: str = Field(
        ...,
        description="Concise topic heading (e.g., 'Quarterly Budget & Schedule Updates')",
    )
    bullets: List[str] = Field(
        ...,
        min_length=1,
        description="1 to 4 concise bullet points summarizing decisions, facts, or updates for this topic",
    )


class MeetingNotesOutput(BaseModel):
    """Structured meeting notes output generated by Ollama."""
    title: str = Field(
        ...,
        description="Concise, specific 4-7 word meeting title",
    )
    summary: str = Field(
        ...,
        description="2-3 sentence executive summary covering core purpose and outcome",
    )
    takeaways: List[TopicTakeaway] = Field(
        ...,
        min_length=1,
        description="Key discussion topics grouped with bulleted takeaways (at least 1 topic required)",
    )
    action_items: List[ExtractedActionItem] = Field(
        default_factory=list,
        description="List of action items extracted from the transcript",
    )


# ==============================================================================
# SQLite & REST API Models
# ==============================================================================

class ActionItemDB(BaseModel):
    """Action item persisted in SQLite database."""
    id: str = Field(..., description="Server-generated UUIDv4 identifier")
    meeting_id: int = Field(..., description="Foreign key referencing meetings(id)")
    owner: str = Field(..., description="Owner name, 'Me' if assigned to the user")
    task: str = Field(..., description="Task description")
    due_date: Optional[str] = Field(default=None, description="Optional deadline")
    done: bool = Field(default=False, description="Completion status (False=open, True=completed)")
    position: int = Field(default=0, description="Display order position")


class ActionItemCreate(BaseModel):
    """Payload to manually add an action item to an existing meeting."""
    owner: str = Field(default="Me", description="Action item assignee")
    task: str = Field(..., description="Action item description")
    due_date: Optional[str] = Field(default=None, description="Optional deadline")


class ActionItemUpdate(BaseModel):
    """Payload to update an action item (e.g. checkbox toggle, editing text)."""
    owner: Optional[str] = None
    task: Optional[str] = None
    due_date: Optional[str] = None
    done: Optional[bool] = None
    position: Optional[int] = None


class MeetingResponse(BaseModel):
    """Full meeting model returned to the frontend."""
    id: int
    title: str
    created_at: str
    updated_at: str
    duration_seconds: int = 0
    summary: str
    takeaways: List[Any] = Field(default_factory=list)
    asr_model: str
    llm_model: str
    action_items: List[ActionItemDB] = Field(default_factory=list)


class MeetingUpdateRequest(BaseModel):
    """Payload for inline edits of meeting title, summary, or takeaways."""
    title: Optional[str] = None
    summary: Optional[str] = None
    takeaways: Optional[List[Any]] = None


class HealthResponse(BaseModel):
    """System health and operational state response."""
    status: str = "ok"
    session_state: str = "IDLE"  # IDLE, RECORDING, SUMMARIZING, SUMMARIZATION_FAILED
    ollama_reachable: bool = False
    available_models: List[str] = Field(default_factory=list)
    audio_devices: List[Dict[str, Any]] = Field(default_factory=list)


class MeetingStartRequest(BaseModel):
    """Request to initiate a live meeting recording session."""
    mic_device_id: Optional[int] = None
    system_device_id: Optional[int] = None
    asr_model: Optional[str] = None


class MeetingStopRequest(BaseModel):
    """Request to end recording and trigger summarization."""
    llm_model: Optional[str] = None


class MeetingRetryRequest(BaseModel):
    """Request to re-run summarization on the in-memory transcript."""
    llm_model: Optional[str] = None

